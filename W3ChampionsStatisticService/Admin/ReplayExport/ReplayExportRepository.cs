using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using MongoDB.Bson;
using MongoDB.Driver;
using W3C.Contracts.Matchmaking;
using W3C.Domain.CommonValueObjects;
using W3C.Domain.Repositories;
using W3C.Domain.Tracing;
using W3ChampionsStatisticService.Matches;
using W3ChampionsStatisticService.Ports;

namespace W3ChampionsStatisticService.Admin.ReplayExport;

[Trace]
public class ReplayExportRepository(
    MongoClient mongoClient,
    IPatchRepository patchRepository,
    IMatchRepository matchRepository,
    IRankRepository rankRepository) : MongoDbRepositoryBase(mongoClient)
{
    /// <summary>
    /// Upper limit for one download. Each replay is generated by replay-service, and a replay is about
    /// 250 KB: 5,000 replays make a ZIP of about 1.25 GB. Raise it when real downloads show that it is safe.
    /// </summary>
    public const int MaxQuantity = 5_000;

    /// <summary>The games of the first table page come with the search; the next pages come with <see cref="LoadByIds(IReadOnlyList{ObjectId})"/>.</summary>
    public const int FirstPageSize = 25;

    /// <summary>The largest table page.</summary>
    public const int MaxPageSize = 250;

    /// <summary>
    /// Upper limit for left-out games in one search. Mongo gets them as one $nin list (about 20 bytes per
    /// game), and a query must stay below 16 MB.
    /// </summary>
    public const int MaxExcluded = 500_000;

    /// <summary>The preview stops counting here, so a broad filter cannot scan the whole collection.</summary>
    public const int CountLimit = 100_000;

    /// <summary>
    /// A random sample comes from the newest matching games, at most this many. $sample over all matching
    /// games would read and sort every one of them.
    /// </summary>
    public const int RandomPool = 100_000;

    /// <summary>
    /// Time limits of the search queries. A rare combination that no index supports (for example a high MMR
    /// range in all seasons) must not keep the database busy: Mongo stops the query, and the user gets a
    /// clear message.
    /// </summary>
    public static readonly TimeSpan SearchTimeLimit = TimeSpan.FromSeconds(20);

    /// <summary>When the count hits its limit, the preview shows "N+ games" with the games it found.</summary>
    public static readonly TimeSpan CountTimeLimit = TimeSpan.FromSeconds(10);

    private readonly IPatchRepository _patchRepository = patchRepository;
    private readonly IMatchRepository _matchRepository = matchRepository;
    private readonly IRankRepository _rankRepository = rankRepository;

    /// <summary>The choices of the search form for <paramref name="gameMode"/>, and the prices of the page.</summary>
    public async Task<ReplayExportOptions> LoadOptions(GameMode gameMode, ReplayExportPrices prices) => new()
    {
        Patches = await LoadPatchOptions(),
        Seasons = await LoadSeasons(),
        MapNames = await LoadMapNames(gameMode),
        MaxQuantity = MaxQuantity,
        Prices = prices,
    };

    public async Task<List<ReplayExportPatchOption>> LoadPatchOptions()
    {
        return ReplayExportQuery.PatchOptions(await _patchRepository.LoadPatches());
    }

    public async Task<List<int>> LoadSeasons()
    {
        return (await _rankRepository.LoadSeasons()).Select(s => s.Id).OrderByDescending(id => id).ToList();
    }

    public async Task<List<string>> LoadMapNames(GameMode gameMode)
    {
        var season = await _matchRepository.LoadLastSeason();
        return season == null ? [] : await _matchRepository.LoadMapNames(season.Id, gameMode);
    }

    public async Task<ReplayExportPreview> Preview(ReplayExportFilter filter, IReadOnlyCollection<ObjectId> excludedIds)
    {
        var patches = await LoadPatchOptions();
        var collection = CreateCollection<Matchup>();
        var playerTextSearch = !string.IsNullOrWhiteSpace(filter.BattleTag) && await HasPlayerTextIndex(collection);
        var query = ReplayExportQuery.Build(filter, patches, excludedIds, playerTextSearch);
        var quantity = Math.Clamp(filter.Quantity, 1, MaxQuantity);

        using var stopCount = new CancellationTokenSource();
        var count = CountMatching(collection, query, stopCount.Token);
        var search = new FindOptions { MaxTime = SearchTimeLimit };
        List<ObjectId> ids;
        try
        {
            ids = filter.Order switch
            {
                ReplayExportOrder.Random => await RandomSample(collection, query, quantity),
                ReplayExportOrder.Oldest => await FindIds(collection.Find(query, search).SortBy(m => m.Id), quantity),
                _ => await FindIds(collection.Find(query, search).SortByDescending(m => m.Id), quantity),
            };
        }
        catch
        {
            // Without the list, the count has no use: stop it, and wait so that its errors are not lost.
            await stopCount.CancelAsync();
            await Task.WhenAny(count);
            throw;
        }

        var (total, complete) = await count;
        return new ReplayExportPreview
        {
            // An incomplete count is at least the number of games found.
            TotalMatching = Math.Max(total, ids.Count),
            TotalIsCapped = !complete || total >= CountLimit,
            MatchIds = ids.Select(id => id.ToString()).ToList(),
            Matches = await LoadByIds(ids.Take(FirstPageSize).ToList(), patches),
        };
    }

    /// <summary>Only the ids: the games of a table page are loaded when the page shows it.</summary>
    private static async Task<List<ObjectId>> FindIds(IFindFluent<Matchup, Matchup> find, int quantity)
    {
        var documents = await find.Limit(quantity).Project(Builders<Matchup>.Projection.Include(m => m.Id)).ToListAsync();
        return documents.Select(d => d["_id"].AsObjectId).ToList();
    }

    /// <summary>The number of matching games, up to <see cref="CountLimit"/>. Complete is false when the time limit stopped the count.</summary>
    private static async Task<(long Total, bool Complete)> CountMatching(
        IMongoCollection<Matchup> collection,
        FilterDefinition<Matchup> query,
        CancellationToken cancellationToken)
    {
        try
        {
            var options = new CountOptions { Limit = CountLimit, MaxTime = CountTimeLimit };
            return (await collection.CountDocumentsAsync(query, options, cancellationToken), true);
        }
        catch (MongoExecutionTimeoutException)
        {
            return (0, false);
        }
    }

    /// <summary>
    /// True when Matchup has the text index on Team1Players–Team4Players. MatchRepository builds it at
    /// startup, so it normally exists; without it, the player search still works, only slower.
    /// </summary>
    public static async Task<bool> HasPlayerTextIndex(IMongoCollection<Matchup> collection)
    {
        var indexes = await (await collection.Indexes.ListAsync()).ToListAsync();
        string[] fields = ["Team1Players", "Team2Players", "Team3Players", "Team4Players"];
        return indexes.Any(index =>
            index.TryGetValue("weights", out var weights)
            && weights.IsBsonDocument
            && fields.All(weights.AsBsonDocument.Contains));
    }

    /// <summary>
    /// A random sample of the newest <see cref="RandomPool"/> matching games. An index gives the games in
    /// _id order, and only their ids go into $sample, so the sort needs little memory. The player text
    /// search gives the games in no order: then Mongo sorts them, on disk when they are many. The list
    /// shows the sample newest first.
    /// </summary>
    private static async Task<List<ObjectId>> RandomSample(IMongoCollection<Matchup> collection, FilterDefinition<Matchup> query, int quantity)
    {
        var sampled = await collection
            .Aggregate(new AggregateOptions { MaxTime = SearchTimeLimit, AllowDiskUse = true })
            .Match(query)
            .SortByDescending(m => m.Id)
            .Limit(RandomPool)
            .Project(Builders<Matchup>.Projection.Include(m => m.Id))
            .Sample(quantity)
            .ToListAsync();

        return sampled.Select(d => d["_id"].AsObjectId).OrderByDescending(id => id).ToList();
    }

    /// <summary>
    /// The games of the user's past downloads that the filter leaves out: all of them, or the selected ones.
    /// Downloads of other users never count. <paramref name="onlyPurchases"/>: only the paid purchases (the
    /// store), not the free admin downloads.
    /// </summary>
    public async Task<HashSet<ObjectId>> LoadExcludedIds(ReplayExportFilter filter, string battleTag, bool onlyPurchases = false)
    {
        var ids = new HashSet<ObjectId>();
        if (!filter.ExcludePastDownloads) return ids;

        var exportIds = (filter.ExcludeExportIds ?? [])
            .Select(id => ObjectId.TryParse(id, out var objectId) ? objectId : ObjectId.Empty)
            .Where(id => id != ObjectId.Empty)
            .ToList();
        var downloads = onlyPurchases ? PurchasesOf(battleTag) : Builders<ReplayExportRecord>.Filter.Eq(e => e.RequestedBy, battleTag);
        if (exportIds.Count > 0) downloads &= Builders<ReplayExportRecord>.Filter.In(e => e.Id, exportIds);

        var exported = await Exports.Find(downloads).Project(e => e.MatchIds).ToListAsync();
        foreach (var matchIds in exported) ids.UnionWith(matchIds);
        return ids;
    }

    /// <summary>The user's past downloads, newest first, without the game ids.</summary>
    public Task<List<ReplayExportSummary>> LoadExports(string battleTag) =>
        LoadSummaries(Builders<ReplayExportRecord>.Filter.Eq(e => e.RequestedBy, battleTag), 500);

    /// <summary>
    /// The user's paid purchases from the replay store, newest first. Free admin downloads are not purchases.
    /// Admins can download a purchase too (all-exports): the buyer sees only their own downloads.
    /// </summary>
    public async Task<List<ReplayExportSummary>> LoadPurchases(string battleTag)
    {
        var purchases = await LoadSummaries(PurchasesOf(battleTag), 500);
        foreach (var purchase in purchases)
        {
            var own = purchase.Downloads.Where(d => d.By == battleTag).ToList();
            if (own.Count == purchase.Downloads.Count) continue;
            purchase.Downloads = own;
            purchase.DownloadCount = own.Count;
            purchase.LastDownloadedAt = own.Count > 0 ? own.Max(d => d.At) : default;
        }
        return purchases;
    }

    /// <summary>For the account menu of every signed-in user: uses the RequestedBy index.</summary>
    public Task<long> CountPurchases(string battleTag) => Exports.CountDocumentsAsync(PurchasesOf(battleTag));

    private static FilterDefinition<ReplayExportRecord> PurchasesOf(string battleTag) =>
        Builders<ReplayExportRecord>.Filter.Eq(e => e.RequestedBy, battleTag) & Builders<ReplayExportRecord>.Filter.Eq(e => e.Charged, true);

    /// <summary>For admins: the downloads of all users, or of one user, newest first.</summary>
    public Task<List<ReplayExportSummary>> LoadAllExports(string user)
    {
        var filter = string.IsNullOrWhiteSpace(user)
            ? FilterDefinition<ReplayExportRecord>.Empty
            : Builders<ReplayExportRecord>.Filter.Eq(e => e.RequestedBy, user.Trim());
        return LoadSummaries(filter, 2000);
    }

    private async Task<List<ReplayExportSummary>> LoadSummaries(FilterDefinition<ReplayExportRecord> filter, int limit)
    {
        var records = await Exports
            .Find(filter)
            .SortByDescending(e => e.Id)
            .Limit(limit)
            .Project(e => new
            {
                e.Id,
                e.CreatedAt,
                e.RequestedBy,
                e.Label,
                e.Description,
                e.Requested,
                Count = e.MatchIds.Count,
                e.Failed,
                e.DownloadCount,
                e.LastDownloadedAt,
                e.Downloads,
                e.Price,
                e.Charged,
            })
            .ToListAsync();

        return records.Select(e => new ReplayExportSummary
        {
            Id = e.Id.ToString(),
            CreatedAt = e.CreatedAt,
            RequestedBy = e.RequestedBy,
            Label = e.Label,
            Description = e.Description,
            Requested = e.Requested,
            Count = e.Count,
            Failed = e.Failed,
            DownloadCount = e.DownloadCount,
            LastDownloadedAt = e.LastDownloadedAt,
            Downloads = e.Downloads ?? [],
            Price = e.Price,
            Charged = e.Charged,
        }).ToList();
    }

    /// <summary>One of the user's past downloads, or null when it does not exist or belongs to another user.</summary>
    public async Task<ReplayExportRecord> LoadExport(string id, string battleTag)
    {
        if (!ObjectId.TryParse(id, out var objectId)) return null;
        return await Exports.Find(e => e.Id == objectId && e.RequestedBy == battleTag).FirstOrDefaultAsync();
    }

    /// <summary>For admins: a download of any user.</summary>
    public async Task<ReplayExportRecord> LoadAnyExport(string id)
    {
        if (!ObjectId.TryParse(id, out var objectId)) return null;
        return await Exports.Find(e => e.Id == objectId).FirstOrDefaultAsync();
    }

    public Task SaveExport(ReplayExportRecord record) => Exports.InsertOneAsync(record);

    /// <summary>
    /// Saves a paid purchase. Returns false when the record exists already: the webhook and the return page
    /// can both save the same purchase, also at the same time.
    /// </summary>
    public async Task<bool> SavePurchase(ReplayExportRecord record)
    {
        try
        {
            await Exports.InsertOneAsync(record);
            return true;
        }
        catch (MongoWriteException ex) when (ex.WriteError?.Category == ServerErrorCategory.DuplicateKey)
        {
            return false;
        }
    }

    /// <summary>
    /// The ids of the games that exist and have a FLO replay, in the order of <paramref name="ids"/>. Only the
    /// ids: a purchase checks up to 5,000 games.
    /// </summary>
    public async Task<List<ObjectId>> ReplayableIds(IReadOnlyList<ObjectId> ids)
    {
        if (ids.Count == 0) return [];
        var found = await CreateCollection<Matchup>()
            .Find(Builders<Matchup>.Filter.In(m => m.Id, ids) & Builders<Matchup>.Filter.Gt(m => m.FloMatchId, 0))
            .Project(Builders<Matchup>.Projection.Include(m => m.Id))
            .ToListAsync();
        var replayable = found.Select(d => d["_id"].AsObjectId).ToHashSet();
        return ids.Where(replayable.Contains).ToList();
    }

    /// <summary>Records a repeat download. It adds no games: they are the games of the first download.</summary>
    public Task MarkDownloadedAgain(ObjectId id, string by)
    {
        var now = DateTime.UtcNow;
        return Exports.UpdateOneAsync(
            e => e.Id == id,
            Builders<ReplayExportRecord>.Update
                .Inc(e => e.DownloadCount, 1)
                .Set(e => e.LastDownloadedAt, now)
                .Push(e => e.Downloads, new ReplayExportDownload { By = by, At = now }));
    }

    private IMongoCollection<ReplayExportRecord> Exports => CreateCollection<ReplayExportRecord>("ReplayExports");

    /// <summary>Loads FLO games by id, in the order of <paramref name="ids"/>. Unknown ids are skipped.</summary>
    public async Task<List<ReplayExportMatch>> LoadByIds(IReadOnlyList<ObjectId> ids) => await LoadByIds(ids, await LoadPatchOptions());

    private async Task<List<ReplayExportMatch>> LoadByIds(IReadOnlyList<ObjectId> ids, List<ReplayExportPatchOption> patches)
    {
        if (ids.Count == 0) return [];
        var matches = await CreateCollection<Matchup>()
            .Find(Builders<Matchup>.Filter.In(m => m.Id, ids) & Builders<Matchup>.Filter.Gt(m => m.FloMatchId, 0))
            .ToListAsync();

        var byId = matches.ToDictionary(m => m.Id);
        return ids
            .Where(byId.ContainsKey)
            .Select(id => ToExportMatch(byId[id], patches))
            .ToList();
    }

    private static ReplayExportMatch ToExportMatch(Matchup match, IEnumerable<ReplayExportPatchOption> patches)
    {
        var teams = match.Teams.Select(t => new ReplayExportTeam
        {
            Players = t.Players.Select(p => new ReplayExportPlayer
            {
                BattleTag = p.BattleTag,
                Race = p.Race,
                RndRace = p.RndRace,
                // Hidden as on the public match pages, while the system is not sure about the MMR yet.
                OldMmr = p.OldRankDeviation >= PlayersObfuscator.RankDeviationObfuscationThreshold ? null : p.OldMmr,
                Won = p.Won,
            }).ToList(),
        }).ToList();

        var mmrs = teams.SelectMany(t => t.Players).Where(p => p.OldMmr.HasValue).Select(p => p.OldMmr.Value).ToList();

        return new ReplayExportMatch
        {
            Id = match.ObjectId,
            MatchId = match.MatchId,
            FloMatchId = match.FloMatchId ?? 0,
            StartTime = match.StartTime,
            EndTime = match.EndTime,
            DurationInSeconds = match.DurationInSeconds,
            GameMode = match.GameMode,
            GateWay = match.GateWay,
            Season = match.Season,
            Map = match.Map,
            MapName = match.MapName,
            Patch = ReplayExportQuery.PatchAt(patches, match.EndTime),
            AverageMmr = mmrs.Count > 0 ? (int)Math.Round(mmrs.Average()) : null,
            Teams = teams,
        };
    }
}
